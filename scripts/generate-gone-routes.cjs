#!/usr/bin/env node
/**
 * Validate or explicitly regenerate src/lib/goneRoutes.ts from the reviewed
 * legacy-handle inventory. Release builds use --check so they never rewrite
 * middleware source after checkout; maintainers may use --write before commit.
 */

const fs = require('fs');
const path = require('path');

const LEGACY_JSON_PATH = path.resolve(__dirname, '../src/data/legacyGoneProductHandles.json');
const TS_PATH = path.resolve(__dirname, '../src/lib/goneRoutes.ts');

function readHandles(jsonPath, label) {
  if (!fs.existsSync(jsonPath)) {
    console.log(`[gone-routes] No ${label} inventory found at ${jsonPath}.`);
    return [];
  }

  try {
    const raw = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    if (Array.isArray(raw)) {
      return raw.filter(handle => typeof handle === 'string' && handle.length > 0);
    }
    console.warn(`[gone-routes] ${label} inventory is not an array: ${jsonPath}`);
  } catch (err) {
    console.warn(`[gone-routes] Could not parse ${label} inventory ${jsonPath}: ${err.message}`);
  }
  return [];
}

function main() {
  const handles = readHandles(LEGACY_JSON_PATH, 'verified legacy-product');

  // De-duplicate + sort for stable diffs
  const unique = Array.from(new Set(handles)).sort();

  const ts = `// AUTO-GENERATED by scripts/generate-gone-routes.cjs — do not edit manually.
// Regenerate before commit with: node scripts/generate-gone-routes.cjs --write
// Release builds verify this committed source with: node scripts/generate-gone-routes.cjs --check
//
// Contains Shopify product handles that are KNOWN to be dead (removed from Shopify
// or returning 404/410/500 on the storefront). These get a hard HTTP 410 Gone
// response in middleware.ts so Google drops them from the index faster than a
// 404 would.
//
// Source: src/data/legacyGoneProductHandles.json (reviewed legacy inventory).
//
// Handle count: ${unique.length}

export const GONE_PRODUCT_HANDLES: Set<string> = new Set<string>(${JSON.stringify(unique)});
`;

  const write = process.argv.includes('--write');
  const check = process.argv.includes('--check');
  if (write === check) {
    throw new Error('[gone-routes] Choose exactly one mode: --check for releases or --write before commit.');
  }

  if (write) {
    fs.writeFileSync(TS_PATH, ts, 'utf8');
    console.log(`[gone-routes] Wrote ${TS_PATH} (${unique.length} dead handles)`);
    return;
  }

  if (!fs.existsSync(TS_PATH)) {
    throw new Error('[gone-routes] src/lib/goneRoutes.ts is missing; run this script with --write and commit the result.');
  }
  const committed = fs.readFileSync(TS_PATH, 'utf8');
  if (committed !== ts) {
    throw new Error('[gone-routes] src/lib/goneRoutes.ts is stale; run this script with --write and commit the result before releasing.');
  }
  console.log(`[gone-routes] OK — committed middleware inventory matches ${unique.length} reviewed retired handles.`);
}

main();
