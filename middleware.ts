/**
 * Vercel Edge Middleware (non-Next.js / Vite)
 *
 * Serves the same prerendered or server-rendered HTML to every user agent.
 * This prevents crawler-only 404s and metadata differences while retaining
 * Shopify-backed rendering for products added after the latest deployment.
 */

// ─── Pre-rendered Routes ─────────────────────────────────────────────────────
// Auto-generated by scripts/generate-routes.cjs at build time.
// Includes all static pages and blog posts. Product routes are handled
// dynamically by the SSR path below, so they are NOT in this Set.
// See src/lib/autoRoutes.ts for the full list.

// Legacy regional pages that must 301 redirect to /nri
const LEGACY_REGIONAL_REDIRECT_ROUTES = new Set([
  '/nri/uk',
  '/indian-ethnic-wear-uk',
  '/uk-indian-clothing',
  '/uk-designer-sarees',
]);

// Confirmed one-to-one replacements for legacy product handles that still earn
// Google impressions. Run before the 410/404 checks so ranking signals transfer
// to the same current product instead of being discarded.
const PRODUCT_301_REDIRECTS: Record<string, string> = {
  '/product/green-net-sequins-occasion-lehenga-choli': '/product/green-net-sequins-lehenga-choli-with-dupatta',
  '/product/beads-work-lehenga-choli-in-satin-off-white': '/product/off-white-satin-beads-bridal-lehenga-with-dupatta',
  '/product/light-pink-net-beads-festive-lehenga-choli': '/product/light-pink-net-beads-bridal-lehenga-with-dupatta',
  '/product/rust-orange-georgette-embroidery-occasion-lehenga-choli': '/product/rust-orange-georgette-embroidery-lehenga-choli-with-dupatta',
  '/product/wine-pure-vichitra-embroidery-festive-lehenga-choli': '/product/wine-pure-vichitra-embroidery-lehenga-choli-with-dupatta',
};

// Explicit 410 Gone routes — URLs that have been permanently retired and have
// NO semantic replacement. Only manually confirmed deletions belong here.
//
// Format: full pathname starting with '/'.
// Example: '/collections/some-old-collection', '/some-old-landing-page'
const GONE_ROUTES: Set<string> = new Set<string>([
  // ── Manually maintained entries (add retired URLs from GSC export here) ──
  // Product was deleted from Shopify but still gets GSC impressions (8 imp, 1 click
  // at pos 6.38 as of 2026-07-11). 410 tells Google to drop it from the index
  // immediately, vs. 404 which Google retries for weeks.
  '/product/art-silk-pista-green-groom-wear-thread-work-readymade-sherwani',
]);

// Combine manual GONE_ROUTES with auto-discovered dead product handles from build.
// This produces 410 Gone for any /product/{handle} in the set.
function isGoneProductPath(pathname: string): boolean {
  if (!pathname.startsWith('/product/')) return false;
  const handle = pathname.replace('/product/', '');
  return handle.length > 0 && !handle.includes('/') && GONE_PRODUCT_HANDLES.has(handle);
}

// Helper: emit a 410 Gone response with proper noindex headers.
function return410(): Response {
  const html = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">` +
    `<meta name="viewport" content="width=device-width,initial-scale=1">` +
    `<meta name="robots" content="noindex,nofollow">` +
    `<title>410 Gone — LuxeMia</title></head><body>` +
    `<h1>410 — This page has been permanently removed.</h1>` +
    `<p>The content you were looking for is no longer available.</p>` +
    `<p><a href="/">Return to LuxeMia homepage</a> ` +
    `or <a href="/collections">browse our collections</a>.</p></body></html>`;
  return new Response(html, {
    status: 410,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'public, max-age=86400',
      'X-Robots-Tag': 'noindex, nofollow',
    },
  });
}

function withResponseHeader(response: Response, key: string, value: string): Response {
  const headers = new Headers(response.headers);
  headers.set(key, value);
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

// ─── Main Middleware ─────────────────────────────────────────────────────────

export default async function middleware(request: Request) {
  const response = await routeRequest(request);
  const hostname = new URL(request.url).hostname.toLowerCase();

  // Vercel/Lovable preview URLs remain usable for QA, but can never compete
  // with luxemia.shop in search. The HTTP directive also covers pages whose
  // client-side metadata has not hydrated yet.
  if (hostname !== 'luxemia.shop' && hostname !== 'www.luxemia.shop') {
    return withResponseHeader(response, 'X-Robots-Tag', 'noindex, nofollow');
  }

  return response;
}

async function routeRequest(request: Request): Promise<Response> {
  const url = new URL(request.url);
  const { pathname } = url;

  // ── Canonical domain: redirect www → non-www (301 permanent) ──────────────
  // All canonical URLs in prerendered HTML and sitemap use https://luxemia.shop
  // (non-www). Consolidating ensures GSC treats them as one property and avoids
  // duplicate-content signals across the two versions. Using 301 (not 308) for
  // maximum crawler compatibility (some older crawlers and third-party SEO tools
  // handle 308 inconsistently).
  if (url.hostname === 'www.luxemia.shop') {
    const canonical = new URL(request.url);
    canonical.hostname = 'luxemia.shop';
    return Response.redirect(canonical.toString(), 301);
  }

  if (pathname.length > 1 && pathname.endsWith('/')) {
    const canonical = new URL(request.url);
    canonical.pathname = pathname.replace(/\/+$/, '');
    return Response.redirect(canonical.toString(), 301);
  }

  // Featured duplicated New Arrivals product-for-product. Consolidate the old
  // URL so shoppers and search engines have one current discovery page.
  if (pathname === '/bestsellers') {
    return Response.redirect(new URL('/new-arrivals', request.url).toString(), 301);
  }

  // Merchant Center fetches this stable public URL. Generate the feed from
  // live Shopify data instead of serving the empty static placeholder.
  if (pathname === '/merchant-feed.xml') {
    return rewrite(new URL('/api/merchant-feed', request.url));
  }

  // Skip non-page requests (static files, API, etc.)
  if (
    pathname.startsWith('/_prerender') ||
    pathname.startsWith('/assets') ||
    pathname.startsWith('/api') ||
    pathname.startsWith('/catalogs') ||
    pathname.includes('.')
  ) {
    return next();
  }

  // Strip query parameters from collection/category filter URLs for every
  // client. Serving the same response to crawlers and shoppers avoids
  // user-agent-dependent rendering while keeping filtered URLs out of search.
  // URLs like /lehengas?sub=wedding-guest or /sarees?color=red should NOT be
  // indexed as separate pages — they cause duplicate content and waste crawl
  // budget. Serve the canonical category page with a noindex header so Google
  // drops the parameterized URL from the index.
  if (url.search) {
    const cleanPath = pathname; // without query params
    // Only strip params from known category/collection routes
    const CATEGORY_ROUTES = new Set([
      '/lehengas', '/sarees', '/suits', '/menswear', '/jewelry',
      '/indowestern', '/new-arrivals', '/collections',
    ]);
    if (CATEGORY_ROUTES.has(cleanPath) || cleanPath.startsWith('/collections/')) {
      // Return the clean URL's content but with noindex to drop the param URL
      if (PRERENDERED_ROUTES.has(cleanPath)) {
        const prerenderPath = cleanPath === '/'
          ? '/_prerender/index.html'
          : `/_prerender${cleanPath}.html`;
        const resp = await fetch(new URL(prerenderPath, request.url));
        if (resp) {
          const html = await resp.text();
          return new Response(html, {
            status: 200,
            headers: {
              'Content-Type': 'text/html; charset=utf-8',
              'X-Robots-Tag': 'noindex, follow',
              'Link': `<https://luxemia.shop${cleanPath}>; rel="canonical"`,
            },
          });
        }
      }
      return return404(request);
    }
  }

  // Preserve search equity when a legacy product has a confirmed replacement.
  if (PRODUCT_301_REDIRECTS[pathname]) {
    return Response.redirect(new URL(PRODUCT_301_REDIRECTS[pathname], request.url).toString(), 301);
  }

  // 410 Gone check — explicit, confirmed retired URLs only.
  // Confirmed replacement redirects above take precedence; every remaining
  // retired URL stays 410 instead of falling through to a generic redirect.
  if (GONE_ROUTES.has(pathname) || isGoneProductPath(pathname)) {
    return return410();
  }

  // 301 Permanent Redirect for legacy regional pages
  if (LEGACY_REGIONAL_REDIRECT_ROUTES.has(pathname)) {
    return Response.redirect(new URL('/nri', request.url).toString(), 301);
  }

  // 301 Permanent Redirect for canonical URL aliases
  if (pathname === '/privacy-policy') {
    return Response.redirect(new URL('/privacy', request.url).toString(), 301);
  }
  if (pathname === '/terms-of-service') {
    return Response.redirect(new URL('/terms', request.url).toString(), 301);
  }
  // /products has no React route — redirect to /collections to prevent soft 404
  if (pathname === '/products') {
    return Response.redirect(new URL('/collections', request.url).toString(), 301);
  }
  // /virtual-try-on feature has been retired — 301 redirect to homepage so any
  // old bookmarks or indexed URLs pass link equity to the homepage instead of 404.
  if (pathname === '/virtual-try-on') {
    return Response.redirect(new URL('/', request.url).toString(), 301);
  }
  // 301 Permanent Redirect for /collections/* → canonical category pages.
  // These routes exist as client-side React Router <Navigate> redirects, but
  // bots need server-side 301s to properly transfer link equity and avoid
  // indexing the redirect-source URL with thin/empty SPA content.
  const COLLECTION_301_REDIRECTS: Record<string, string> = {
    '/collections/wedding-sarees': '/sarees',
    '/collections/bridal-lehengas': '/lehengas',
    '/collections/reception-outfits': '/collections',
    '/collections/festive-wear': '/collections',
    '/collections/sarees': '/sarees',
    '/collections/salwar-kameez': '/suits',
    '/collections/suits': '/suits',
    '/collections/menswear': '/menswear',
    '/collections/lehengas': '/lehengas',
    '/collections/sharara-suits': '/suits',
    '/collections/gharara-suits': '/suits',
    '/collections/anarkali-suits': '/suits',
    '/collections/pakistani-suits': '/suits',
    '/collections/pakistani-wedding-dresses': '/suits',
    '/collections/party-wear-lehengas': '/lehengas',
    '/collections/wedding-lehengas': '/lehengas',
    '/collections/designer-sarees': '/sarees',
    '/collections/indo-western': '/indowestern',
    '/collections/bridesmaid-dresses': '/sarees',
    '/collections/groomsman-outfits': '/menswear',
    '/collections/lehenga-choli': '/lehengas',
  };
  if (COLLECTION_301_REDIRECTS[pathname]) {
    return Response.redirect(new URL(COLLECTION_301_REDIRECTS[pathname], request.url).toString(), 301);
  }

  // Product pages use one response path for crawlers and shoppers. Existing
  // prerenders are fastest; products added since the latest deployment fall
  // back to live Shopify rendering. Missing handles always return a true 404.
  if (pathname.startsWith('/product/')) {
    const handle = pathname.replace('/product/', '');
    if (!handle || handle.includes('/')) {
      return return404(request);
    }
    if (PRERENDERED_PRODUCT_HANDLES.has(handle)) {
      return rewrite(new URL(`/_prerender/product/${handle}.html`, request.url));
    }

    const product = await fetchProductByHandle(handle);
    if (product) {
      const canonicalUrl = `https://luxemia.shop/product/${handle}`;
      return new Response(generateProductHtml(product, canonicalUrl), {
        status: 200,
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'public, max-age=600, s-maxage=3600, stale-while-revalidate=86400',
          'X-Robots-Tag': 'index, follow',
        },
      });
    }

    const jewelryProduct = getJewelryProductByHandle(handle);
    if (jewelryProduct) {
      const canonicalUrl = `https://luxemia.shop/product/${handle}`;
      return new Response(generateJewelryProductHtml(jewelryProduct, canonicalUrl), {
        status: 200,
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'public, max-age=600, s-maxage=3600, stale-while-revalidate=86400',
          'X-Robots-Tag': 'index, follow',
        },
      });
    }

    return return404(request);
  }

  // Preserve SEO equity for legacy size-guide URLs before the bot unknown-route
  // fallback, so crawlers receive the same 301 as normal visitors.
  const LEGACY_BLOG_REDIRECTS: Record<string, string> = {
    '/blog/indian-size-to-us-clothing-size-conversion-guide': '/sizing-measurements-guide',
    '/blog/indian-size-to-us-size-conversion-chart': '/sizing-measurements-guide',
  };
  if (LEGACY_BLOG_REDIRECTS[pathname]) {
    return Response.redirect(new URL(LEGACY_BLOG_REDIRECTS[pathname], request.url).toString(), 301);
  }

  // Every public indexable route is served from the same prerendered file to
  // every user agent. This removes the Googlebot-only branch that caused 52
  // valid URLs to return 404 after the July 23 migration deployment.
  if (PRERENDERED_ROUTES.has(pathname)) {
    const prerenderPath =
      pathname === '/'
        ? '/_prerender/index.html'
        : `/_prerender${pathname}.html`;
    return rewrite(new URL(prerenderPath, request.url));
  }

  // Account and administrative pages stay functional but are excluded from
  // search at the HTTP layer, before any client-side React metadata runs.
  const PRIVATE_SPA_ROUTES = new Set([
    '/wishlist',
    '/auth',
    '/account',
    '/admin',
    '/order-confirmation',
  ]);
  if (PRIVATE_SPA_ROUTES.has(pathname) || pathname.startsWith('/admin/')) {
    return withResponseHeader(next(), 'X-Robots-Tag', 'noindex, nofollow');
  }

  // No public route matched: return the same real 404 to shoppers, Googlebot,
  // social scrapers, and SEO tools. This eliminates remaining soft cloaking.
  return return404(request);
}

