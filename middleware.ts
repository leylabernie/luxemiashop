function returnShopifyUnavailable(): Response {
  const html = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">` +
    `<meta name="viewport" content="width=device-width,initial-scale=1">` +
    `<title>Temporarily unavailable — LuxeMia</title></head><body>` +
    `<h1>This page is temporarily unavailable.</h1>` +
    `<p>Please try again shortly.</p></body></html>`;
  return new Response(html, {
    status: 503,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'no-store',
      'Retry-After': '60',
    },
  });
}

function withResponseHeader(response: Response, key: string, value: string): Response {
  const headers = new Headers(response.headers);
  headers.set(key, value);
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

// Query parameters that create filter, sort, grid, or internal-search URL noise.
// These URLs remain usable for shoppers, but should not become separate organic
// landing pages. Product ?variant= is intentionally excluded: it may be a valid
// product-variant or Merchant landing URL and receives canonical-only handling.
const INDEXATION_NOISE_PARAMS = new Set<string>([
  'sort_by',
  'sort',
  'filter',
  'grid',
  'q',
  'sub',
  'color',
  'fabric',
  'size',
  'price_min',
  'price_max',
  'price',
  'work',
  'style',
  'occasion',
  'availability',
  'gender',
  'section_id',
]);

function isIndexationNoiseParam(name: string): boolean {
  const normalized = name.toLowerCase();
  return (
    INDEXATION_NOISE_PARAMS.has(normalized)
    || normalized.startsWith('filter.')
    || normalized.startsWith('filter[')
    || normalized.startsWith('options[')
  );
}

function hasIndexationNoiseParams(searchParams: URLSearchParams): boolean {
  for (const name of searchParams.keys()) {
    if (isIndexationNoiseParam(name)) return true;
  }
  return false;
}

// Known search, shopping, ad, email, and social attribution parameters. These
// never change visible page content: they must NEVER trigger noindex or 404 on
// canonical collection/product routes, and may be preserved across canonical
// 301 redirects so Google/Meta/Pinterest/email attribution stays intact.
const ALLOWED_ATTRIBUTION_PARAMS = new Set<string>([
  '_ga',
  '_gl',
  'srsltid',
  'gclid',
  'gbraid',
  'wbraid',
  'gclsrc',
  'gad_source',
  'gad_campaignid',
  'dclid',
  'msclkid',
  'fbclid',
  'ttclid',
  'twclid',
  'epik',
  'mc_cid',
  'mc_eid',
]);

function isAllowedAttributionParam(name: string): boolean {
  const normalized = name.toLowerCase();
  return ALLOWED_ATTRIBUTION_PARAMS.has(normalized) || /^utm_[a-z0-9_]+$/.test(normalized);
}

function copyAllowedAttributionParams(source: URLSearchParams, target: URL): URL {
  for (const [name, value] of source) {
    if (isAllowedAttributionParam(name)) {
      target.searchParams.append(name, value);
    }
  }
  return target;
}

function getCleanFacetCanonicalPath(url: URL): string {
  const subcategory = url.searchParams.get('sub');
  const category = url.pathname.match(/^\/(lehengas|sarees|suits|menswear|jewelry)$/)?.[1];
  return category && subcategory
    ? getDedicatedSubcategoryPath(category, subcategory) || url.pathname
    : url.pathname;
}

function getLegacyFacetRedirectPath(url: URL): string | null {
  const nonAttributionNames = [...url.searchParams.keys()].filter(
    (name) => !isAllowedAttributionParam(name),
  );
  if (nonAttributionNames.length !== 1 || nonAttributionNames[0].toLowerCase() !== 'sub') return null;

  const canonicalPath = getCleanFacetCanonicalPath(url);
  return canonicalPath !== url.pathname ? canonicalPath : null;
}

function isPublicHtmlPath(pathname: string): boolean {
  if (pathname.includes('.')) return false;

  const nonPublicPrefixes = [
    '/_prerender',
    '/assets',
    '/api',
    '/catalogs',
    '/admin',
    '/account',
    '/auth',
    '/wishlist',
    '/cart',
    '/checkout',
    '/order-confirmation',
    '/meta-checkout',
  ];

  return !nonPublicPrefixes.some(
    (prefix) => pathname === prefix || pathname.startsWith(`${prefix}/`),
  );
}

function withCanonicalQuerySignals(request: Request, response: Response): Response {
  const url = new URL(request.url);
  if (!url.search || response.status !== 200 || !isPublicHtmlPath(url.pathname)) {
    return response;
  }

  const existingRobots = response.headers.get('X-Robots-Tag')?.toLowerCase() || '';
  if (existingRobots.includes('nofollow')) return response;

  const headers = new Headers(response.headers);
  headers.set('Link', `<https://luxemia.shop${getCleanFacetCanonicalPath(url)}>; rel="canonical"`);

  if (hasIndexationNoiseParams(url.searchParams)) {
    headers.set('X-Robots-Tag', 'noindex, follow');
  }

  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

// ─── Main Middleware ─────────────────────────────────────────────────────────

export default async function middleware(request: Request) {
  let response = await routeRequest(request);
  response = withCanonicalQuerySignals(request, response);
  const hostname = new URL(request.url).hostname.toLowerCase();

  // Vercel/Lovable preview URLs remain usable for QA, but can never compete
  // with luxemia.shop in search. The HTTP directive also covers pages whose
  // client-side metadata has not hydrated yet.
  if (hostname !== 'luxemia.shop' && hostname !== 'www.luxemia.shop') {
    return withResponseHeader(response, 'X-Robots-Tag', 'noindex, nofollow');
  }

  return response;
}

async function routeRequest(request: Request): Promise<Response> {
  const url = new URL(request.url);
  const { pathname } = url;

  // ── Canonical origin: redirect HTTP/www → HTTPS apex (301 permanent) ──────
  // All canonical URLs in prerendered HTML and sitemap use https://luxemia.shop
  // (non-www). Consolidating ensures GSC treats them as one property and avoids
  // duplicate-content signals across the two versions. Using 301 (not 308) for
  // maximum crawler compatibility (some older crawlers and third-party SEO tools
  // handle 308 inconsistently).
  if (
    (url.hostname === 'www.luxemia.shop' || url.hostname === 'luxemia.shop')
    && (url.hostname !== 'luxemia.shop' || url.protocol !== 'https:')
  ) {
    const canonical = new URL(request.url);
    canonical.hostname = 'luxemia.shop';
    canonical.protocol = 'https:';
    canonical.port = '';
    return Response.redirect(canonical.toString(), 301);
  }

  if (pathname.length > 1 && pathname.endsWith('/')) {
    const canonical = new URL(request.url);
    canonical.pathname = pathname.replace(/\/+$/, '');
    return Response.redirect(canonical.toString(), 301);
  }

  // Shopify handles are canonical without dangling hyphens. Normalize only a
  // single nonempty product segment and preserve variant/attribution queries.
  const trailingProductHyphen = pathname.match(/^\/product\/([a-z0-9](?:[a-z0-9-]*[a-z0-9])?)-+$/i);
  if (trailingProductHyphen) {
    const canonical = new URL(request.url);
    canonical.pathname = `/product/${trailingProductHyphen[1]}`;
    return Response.redirect(canonical.toString(), 301);
  }

  // Merchant Center checkout links select the exact feed variant and quantity.
  // Keep the cart permalink on LuxeMia's origin for the feed, then hand off to
  // Shopify's hosted checkout. Only forward known attribution parameters; never
  // pass user-controlled return URLs or arbitrary redirect targets to Shopify.
  // Feed IDs may be numeric or composite; pass only their trailing variant ID to Shopify.
  const merchantCartMatch = pathname.match(/^\/cart\/(?:[a-z0-9][a-z0-9-]*-(?:v)?)?(\d+):1$/i);
  if (merchantCartMatch && (request.method === 'GET' || request.method === 'HEAD')) {
    const variantId = merchantCartMatch[1];
    const checkout = copyAllowedAttributionParams(
      url.searchParams,
      new URL(`https://lovable-project-zlh0w.myshopify.com/cart/${variantId}:1`),
    );
    return new Response(null, {
      status: 302,
      headers: {
        'Location': checkout.toString(),
        'Cache-Control': 'no-store',
      },
    });
  }

  // Featured duplicated New Arrivals product-for-product. Consolidate the old
  // URL so shoppers and search engines have one current discovery page.
  if (pathname === '/bestsellers') {
    return Response.redirect(new URL('/new-arrivals', request.url).toString(), 301);
  }

  // Static assets and machine-readable files (including merchant-feed.xml) are
  // served directly by Vercel. The feed is generated and validated at build time.
  if (
    pathname.startsWith('/_prerender') ||
    pathname.startsWith('/assets') ||
    pathname.startsWith('/api') ||
    pathname.startsWith('/catalogs') ||
    pathname.includes('.')
  ) {
    return next();
  }

  // 301 Permanent Redirect for /collections/* → canonical category pages.
  // Run BEFORE the parameterized collection block so ad/shopping/social links
  // like /collections/sarees?srsltid=... or /collections/wedding-lehengas?gclid=...
  // cleanly 301 to their canonical category instead of returning 404.
  const COLLECTION_301_REDIRECTS: Record<string, string> = {
    '/collections/earrings': '/jewelry',
    '/collections/evening-gowns': '/collections',
    '/collections/frontpage': '/',
    '/collections/jacket-sets': '/suits',
    '/collections/kurta-pajama-vest': '/menswear',
    '/collections/manthrakodi-sarees': '/sarees',
    '/collections/saree-gowns': '/sarees',
    '/collections/reception-outfits': '/collections',
    '/collections/festive-wear': '/collections',
    '/collections/sarees': '/sarees',
    '/collections/salwar-kameez': '/suits',
    '/collections/suits': '/suits',
    '/collections/menswear': '/menswear',
    '/collections/lehengas': '/lehengas',
    '/collections/pakistani-suits': '/suits',
    '/collections/pakistani-wedding-dresses': '/suits',
    '/collections/wedding-lehengas': '/lehengas',
    '/collections/indo-western': '/indowestern',
    '/collections/bridesmaid-dresses': '/sarees',
    '/collections/groomsman-outfits': '/menswear',
    '/collections/lehenga-choli': '/lehengas',
    // Canonical category aliases observed in production 4xx logs. Each
    // destination is the existing final 200, self-canonical route.
    '/collections/jewelry': '/jewelry',
    '/collections/new-arrivals': '/new-arrivals',
    '/collections/indowestern': '/indowestern',
    '/collections/nri': '/nri',
  };
  if (COLLECTION_301_REDIRECTS[pathname]) {
    const redirectTarget = copyAllowedAttributionParams(
      url.searchParams,
      new URL(COLLECTION_301_REDIRECTS[pathname], request.url),
    );
    return Response.redirect(redirectTarget.toString(), 301);
  }

  // Handle query parameters on collection/category routes:
  // - Single legacy ?sub=<slug> (with optional attribution params) 301s to its
  //   dedicated canonical landing page.
  // - Filter/sort/search noise params (?color=, ?sort=, ?sub=, ?price=, etc.)
  //   return canonical prerendered HTML with X-Robots-Tag: noindex, follow so
  //   faceted duplicates stay out of search.
  // - Pure attribution/tracking URLs (?srsltid=, ?gclid=, ?utm_*, ?fbclid=,
  //   etc.) MUST remain indexable (200 OK + clean Link: rel="canonical", with
  //   no noindex header) so Google organic/Merchant auto-tagged URLs and paid
  //   landing pages never suppress canonical collection rankings.
  if (url.search) {
    const cleanPath = pathname;
    const CATEGORY_ROUTES = new Set([
      '/lehengas', '/sarees', '/suits', '/menswear', '/jewelry',
      '/indowestern', '/new-arrivals', '/collections',
    ]);
    if (CATEGORY_ROUTES.has(cleanPath) || cleanPath.startsWith('/collections/')) {
      const facetRedirectPath = getLegacyFacetRedirectPath(url);
      if (facetRedirectPath) {
        const redirectTarget = copyAllowedAttributionParams(
          url.searchParams,
          new URL(facetRedirectPath, request.url),
        );
        return Response.redirect(redirectTarget.toString(), 301);
      }

      if (hasIndexationNoiseParams(url.searchParams)) {
        if (PRERENDERED_ROUTES.has(cleanPath)) {
          const prerenderPath = cleanPath === '/'
            ? '/_prerender/index.html'
            : `/_prerender${cleanPath}.html`;
          const resp = await fetch(new URL(prerenderPath, request.url));
          if (resp.ok) {
            const html = await resp.text();
            const canonicalTarget = getCleanFacetCanonicalPath(url);
            return new Response(html, {
              status: 200,
              headers: {
                'Content-Type': 'text/html; charset=utf-8',
                'X-Robots-Tag': 'noindex, follow',
                'Link': `<https://luxemia.shop${canonicalTarget}>; rel="canonical"`,
              },
            });
          }
        }
        return return404(request);
      }
    }
  }

  // Owner-authorized reversible archives must never serve stale prerenders or
  // redirect into an unavailable garment. Do not add these to permanent 410s.
  if (pathname.startsWith('/product/') && isReversiblyArchivedProduct(pathname.slice('/product/'.length))) {
    return return404(request);
  }

  // Preserve search equity when a legacy product has a confirmed replacement.
  if (PRODUCT_301_REDIRECTS[pathname]) {
    const redirectTarget = copyAllowedAttributionParams(
      url.searchParams,
      new URL(PRODUCT_301_REDIRECTS[pathname], request.url),
    );
    return Response.redirect(redirectTarget.toString(), 301);
  }

  // 410 Gone check — explicit, confirmed retired URLs only.
  // Confirmed replacement redirects above take precedence; every remaining
  // retired URL stays 410 instead of falling through to a generic redirect.
  if (GONE_ROUTES.has(pathname) || isGoneProductPath(pathname)) {
    return return410(pathname);
  }

  // 301 Permanent Redirect for legacy regional pages
  if (LEGACY_REGIONAL_REDIRECT_ROUTES.has(pathname)) {
    return Response.redirect(new URL('/nri', request.url).toString(), 301);
  }

  // 301 Permanent Redirect for canonical URL aliases
  if (pathname === '/privacy-policy') {
    return Response.redirect(new URL('/privacy', request.url).toString(), 301);
  }
  if (pathname === '/terms-of-service') {
    return Response.redirect(new URL('/terms', request.url).toString(), 301);
  }
  // Shopify-style page alias still appears in crawl logs; preserve the
  // established contact destination with a single permanent hop.
  if (pathname === '/pages/contact') {
    return Response.redirect(new URL('/contact', request.url).toString(), 301);
  }
  // /products has no React route — redirect to /collections to prevent soft 404
  if (pathname === '/products') {
    return Response.redirect(new URL('/collections', request.url).toString(), 301);
  }
  // The virtual try-on feature has been retired with no semantically equivalent
  // destination. A 410 accurately retires the old URL and avoids an irrelevant
  // homepage redirect that Google can classify as a soft 404.
  if (pathname === '/virtual-try-on') {
    return return410(pathname);
  }

  // Product pages use one response path for crawlers and shoppers. Existing
  // prerenders are fastest; products added since the latest deployment fall
  // back to live Shopify rendering. Missing handles always return a true 404.
  if (pathname.startsWith('/product/')) {
    const handle = pathname.replace('/product/', '');
    if (!handle || handle.includes('/')) {
      return return404(request);
    }
    if (PRERENDERED_PRODUCT_HANDLES.has(handle)) {
      if (!url.searchParams.has('variant')) {
        const staticResponse = await readPrerender(request, `/_prerender/product/${handle}.html`, pathname);
        if (staticResponse) return staticResponse;
      } else {
        const selectedResponse = await renderPrerenderedVariant(request, handle, url.searchParams.get('variant'));
        if (selectedResponse) return selectedResponse;
      }
      // A missing/stale asset must not silently return the wrong selected price.
      // Fall through to the existing live product renderer instead.
    }

    const productLookup = await fetchProductByHandle(handle);
    if (productLookup.status === 'found') {
      const canonicalUrl = `https://luxemia.shop/product/${handle}`;
      let html: string;
      try {
        html = await attachShoppingApp(generateProductHtml(productLookup.product, canonicalUrl,
          url.searchParams.has('variant') ? url.searchParams.get('variant') : undefined), request);
      } catch {
        return returnShopifyUnavailable();
      }
      return new Response(html, {
        status: 200,
        headers: url.searchParams.has('variant') ? VARIANT_HTML_HEADERS : {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'public, max-age=600, s-maxage=3600, stale-while-revalidate=86400',
          'X-Robots-Tag': 'index, follow',
        },
      });
    }

    // Locally catalogued jewelry remains serviceable without Shopify. Every
    // other upstream failure must stay transient instead of becoming a 404.
    const jewelryProduct = getJewelryProductByHandle(handle);
    if (jewelryProduct) {
      const canonicalUrl = `https://luxemia.shop/product/${handle}`;
      let html: string;
      try {
        html = await attachShoppingApp(generateJewelryProductHtml(jewelryProduct, canonicalUrl), request);
      } catch {
        return returnShopifyUnavailable();
      }
      return new Response(html, {
        status: 200,
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'public, max-age=600, s-maxage=3600, stale-while-revalidate=86400',
          'X-Robots-Tag': 'index, follow',
        },
      });
    }

    // Locally catalogued Royal Bridal Silk Vol. 3 styles stay 200/serviceable
    // for homepage & collection internal links until the Shopify import lands,
    // at which point fetchProductByHandle above takes precedence automatically.
    const bridalVol3Product = getBridalVol3ProductByHandle(handle);
    if (bridalVol3Product) {
      const canonicalUrl = `https://luxemia.shop/product/${handle}`;
      const selectedVariant = url.searchParams.get('variant') || undefined;
      let html: string;
      try {
        html = await attachShoppingApp(
          generateProductHtml(bridalVol3Product, canonicalUrl, selectedVariant),
          request,
        );
      } catch {
        return returnShopifyUnavailable();
      }
      return new Response(html, {
        status: 200,
        headers: {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'public, max-age=300, s-maxage=900, stale-while-revalidate=3600',
          'X-Robots-Tag': 'index, follow',
        },
      });
    }

    if (productLookup.status === 'unavailable') {
      return returnShopifyUnavailable();
    }

    return return404(request);
  }

  // Preserve SEO equity for legacy size-guide URLs before the bot unknown-route
  // fallback, so crawlers receive the same 301 as normal visitors.
  const LEGACY_BLOG_REDIRECTS: Record<string, string> = {
    '/blog/indian-size-to-us-clothing-size-conversion-guide': '/blog/indian-to-us-clothing-size-conversion-guide',
    '/blog/indian-size-to-us-size-conversion-chart': '/blog/indian-to-us-clothing-size-conversion-guide',
    // The historic guides no longer have equivalent editorial pages. Send each
    // visitor to the closest live shopping destination rather than a dead URL.
    '/blog/banarasi-silk-saree-guide-authentic': '/collections/silk-sarees',
    '/blog/indian-bridal-jewelry-sets-complete-guide': '/jewelry',
    // Retired guides observed in live 4xx logs. These destinations preserve
    // the same sizing, wedding-guest, menswear, or Mehendi intent.
    '/blog/how-to-measure-yourself-for-a-saree-or-lehenga': '/sizing-measurements-guide',
    '/blog/saree-vs-lehenga-wedding-guest-guide-2026': '/blog/wedding-guest-outfit-ideas',
    '/blog/indian-wedding-guest-outfits-men-usa-guide': '/menswear',
    '/blog/mehendi-outfit-by-role': '/collections/mehendi-outfits',
    // These old slugs are absent from the published articles and topic hubs.
    '/blog/indian-wedding-dress-complete-guide': '/blog',
    '/blog/how-to-choose-perfect-lehenga-wedding-2026': '/blog',
  };
  if (LEGACY_BLOG_REDIRECTS[pathname]) {
    return Response.redirect(new URL(LEGACY_BLOG_REDIRECTS[pathname], request.url).toString(), 301);
  }

  // Only source-backed blog articles and hubs may use the emergency renderer.
  // Query strings do not participate in the static asset lookup.
  const blogMatch = pathname.match(/^\/blog\/([a-z0-9-]+)$/);
  if (blogMatch) {
    const fallbackHtml = generateBlogFallback(blogMatch[1]);
    if (!fallbackHtml) return return404(request);
    if (PRERENDERED_ROUTES.has(pathname)) {
      const staticResponse = await readPrerender(request, `/_prerender${pathname}.html`, pathname);
      if (staticResponse) return staticResponse;
    }
    try {
      const html = await attachShoppingApp(fallbackHtml, request);
      return new Response(html, { status: 200, headers: {
        'Content-Type': 'text/html; charset=utf-8',
        'Cache-Control': 'public, max-age=300, s-maxage=900',
        'X-Robots-Tag': 'index, follow',
      } });
    } catch {
      // A broken app shell is a temporary deployment failure, never a 404.
      return returnShopifyUnavailable();
    }
  }

  // Every public indexable route is served from the same prerendered file to
  // every user agent. This removes the Googlebot-only branch that caused 52
  // valid URLs to return 404 after the July 23 migration deployment.
  if (PRERENDERED_ROUTES.has(pathname)) {
    const prerenderPath =
      pathname === '/'
        ? '/_prerender/index.html'
        : `/_prerender${pathname}.html`;
    return rewrite(new URL(prerenderPath, request.url));
  }

  // Account and administrative pages stay functional but are excluded from
  // search at the HTTP layer, before any client-side React metadata runs.
  const PRIVATE_SPA_ROUTES = new Set([
    '/wishlist',
    '/auth',
    '/account',
    '/admin',
    '/order-confirmation',
    '/meta-checkout',
  ]);
  if (pathname === '/meta-checkout' && metaDiagnosticsEnabled(process.env)) {
    try {
      console.info('[meta-checkout-diagnostic]', JSON.stringify({ stage: 'edge-request', time: new Date().toISOString(), ...metaDiagnosticRequest(request.method, url.searchParams, request.headers) }));
    } catch { /* Diagnostics must never affect checkout. */ }
  }
  if (PRIVATE_SPA_ROUTES.has(pathname) || pathname.startsWith('/admin/')) {
    const privateResponse = next();
    // A redirect response carries no links, and `nofollow` on a 3xx can be read by
    // a crawler as "do not follow this redirect". `/meta-checkout` is one of these
    // routes and answers Meta's checkout validator with a 302, so stamping
    // `nofollow` on it is how "The checkout page couldn't be loaded" can happen
    // even when the redirect itself is correct. Redirects stay noindex; every
    // other response on a private route keeps both directives.
    return withResponseHeader(
      privateResponse,
      'X-Robots-Tag',
      privateResponse.status >= 300 && privateResponse.status < 400 ? 'noindex' : 'noindex, nofollow',
    );
  }

  // No public route matched: return the same real 404 to shoppers, Googlebot,
  // social scrapers, and SEO tools. This eliminates remaining soft cloaking.
  return return404(request);
}

